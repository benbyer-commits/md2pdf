def generate_code_with_fallback(prompt, usage_tracker):
    signatures_context = extract_test_signatures(TESTS_DIR)
    codebase_context = extract_existing_codebase_context(PROJECT_ROOT)
    
    full_prompt = prompt + ("\n" + codebase_context if codebase_context else "") + ("\n" + signatures_context if signatures_context else "")

    total_models = len(CODER_CANDIDATE_MODELS)

    for model_idx, model_name in enumerate(CODER_CANDIDATE_MODELS, start=1):
        print(f"📡 Requesting Groq Coder Agent using model: {model_name} (Candidate {model_idx}/{total_models})")
        
        max_server_retries = 3
        server_retry_count = 0
        max_tokens_val = get_max_tokens_for_model(model_name)

        while server_retry_count < max_server_retries:
            try:
                response = client.chat.completions.create(
                    model=model_name,
                    messages=[
                        {"role": "system", "content": CODER_SYSTEM_PROMPT},
                        {"role": "user", "content": full_prompt}
                    ],
                    temperature=0.2,
                    max_tokens=max_tokens_val
                )

                usage_tracker.record_response(model_name, response)
                
                finish_reason = getattr(response.choices[0], 'finish_reason', None) if response.choices else None
                if finish_reason == 'length':
                    print(f"⚠️ [Truncation Guard] Response from model '{model_name}' reached token limit ({max_tokens_val}). Retrying candidate...")
                    break

                text_content = response.choices[0].message.content if response.choices else ""
                extracted_files = extract_file_blocks(text_content)

                if extracted_files:
                    syntax_errors = []
                    for path, content in extracted_files.items():
                        if path.endswith('.js') or path.endswith('.mjs'):
                            valid, err = validate_js_syntax(content)
                            if not valid:
                                syntax_errors.append((path, err))
                    
                    if syntax_errors:
                        for path, err in syntax_errors:
                            print(f"⚠️ [Syntax Guard Failure] 'node --check' failed on {path}:\n{err}")
                        print("🔄 Retrying generation due to syntax validation errors...\n")
                        break

                    return extracted_files
                else:
                    print(f"⚠️ [Parse Warning] Groq model '{model_name}' produced no extractable file blocks.")
                    print("\n🔍 [DEBUG: Raw Model Output Preview (First 300 chars)]")
                    print("─" * 55)
                    print(text_content[:300] if text_content else "<EMPTY RESPONSE>")
                    print("─" * 55 + "\n")
                    break

            except RateLimitError as e:
                parse_429_error(e, model_name)
                if model_idx < total_models:
                    print(f"🔄 Treating 429 on '{model_name}' as transitory. Falling back to next model ({model_idx+1}/{total_models})...\n")
                    break
                else:
                    print(f"\n🛑 [Hard Error] All {total_models} Groq candidate models failed due to Rate Limits.")
                    usage_tracker.display_summary()
                    sys.exit(1)

            except APIConnectionError as e:
                server_retry_count += 1
                print(f"⚠️ [Connection Warning] Network error contacting Groq endpoint: {e}")
                if server_retry_count < max_server_retries:
                    print(f"🔄 Retrying request ({server_retry_count}/{max_server_retries}) in 3.0s...")
                    time.sleep(3.0)
                else:
                    print(f"⚠️ Network error persisted on model '{model_name}'. Falling back to next candidate model...\n")
                    break

            except InternalServerError as e:
                server_retry_count += 1
                if server_retry_count < max_server_retries:
                    time.sleep(2.0)
                else:
                    sys.exit(1)

            except APIError as e:
                code = getattr(e, 'status_code', None) or getattr(e, 'code', None)
                body = getattr(e, 'body', None) or str(e)
                if code == 429:
                    parse_429_error(e, model_name)
                    if model_idx < total_models:
                        break
                    else:
                        sys.exit(1)
                elif code == 404 or "model_not_found" in str(body):
                    print(f"⚠️ Model '{model_name}' returned 404. Falling back to next candidate model...\n")
                    break
                else:
                    print(f"\n🛑 [API Error ({code})]\n{json.dumps(body, indent=2) if isinstance(body, dict) else body}")
                    sys.exit(1)

            except Exception as e:
                server_retry_count += 1
                if server_retry_count < max_server_retries:
                    time.sleep(2.0)
                else:
                    sys.exit(1)

        print(f"🔄 Switching Groq Coder from '{model_name}' to next candidate model...\n")

    print(f"\n🛑 [Pipeline Failure] All Coder candidate models failed.")
    usage_tracker.display_summary()
    sys.exit(1)

