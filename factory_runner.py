def get_max_tokens_for_model(model_name):
    """Returns safe max_tokens ceiling based on model OTPM limits."""
    if "qwen" in model_name.lower():
        return 800
    return 4096

def validate_js_syntax(file_content):
    """Verifies JavaScript syntax using 'node --check' before writing to disk."""
    try:
        with tempfile.NamedTemporaryFile(suffix='.mjs', mode='w', delete=False, encoding='utf-8') as tmp:
            tmp.write(file_content)
            tmp_path = tmp.name

        res = subprocess.run(['node', '--check', tmp_path], capture_output=True, text=True)
        if os.path.exists(tmp_path):
            os.remove(tmp_path)

        if res.returncode != 0:
            return False, res.stderr.strip()
        return True, ""
    except Exception as e:
        return False, str(e)

def extract_existing_codebase_context(project_root):
    """Reads existing src/ files so the Coder Agent sees exact exports on disk."""
    context_blocks = []
    src_dir = os.path.join(project_root, "src")
    if os.path.exists(src_dir):
        for root, _, files in os.walk(src_dir):
            for file in files:
                if file.endswith('.js') or file.endswith('.mjs'):
                    rel_path = os.path.relpath(os.path.join(root, file), project_root)
                    try:
                        with open(os.path.join(root, file), 'r', encoding='utf-8') as f:
                            code = f.read()
                        context_blocks.append(f"=== EXISTING FILE: {rel_path} ===\n{code}\n=== END EXISTING FILE ===")
                    except Exception:
                        pass
    if context_blocks:
        return "\nEXISTING SOURCE CODE IN REPOSITORY FOR EXPORT MATCHING:\n" + "\n\n".join(context_blocks) + "\n"
    return ""

def extract_test_signatures(tests_dir):
    """Scans test files to extract expected exports and requirements for the Coder prompt."""
    signatures = []
    if not os.path.exists(tests_dir):
        return ""
    
    for root, _, files in os.walk(tests_dir):
        for file in files:
            if file.endswith('.test.js') or file.endswith('.spec.js'):
                path = os.path.join(root, file)
                with open(path, 'r', encoding='utf-8', errors='ignore') as f:
                    lines = f.readlines()
                    for line in lines:
                        clean_line = line.strip()
                        if 'require(' in clean_line or 'import ' in clean_line:
                            signatures.append(f"  - From {file}: {clean_line}")
    
    if signatures:
        return "\nREQUIRED TEST IMPORTS & EXPECTED EXPORTS:\n" + "\n".join(signatures) + "\n"
    return ""

